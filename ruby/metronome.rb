# Description: This project's goal is to help people improve their timing using a metronome.
#              The metronome will include features such as going silent for a few measures and reappearing at random intervals,
#              allowing users to test their internal sense of rhythm.
#              The purpose is to automate this process so the user can keep playing without needing to manually pause or resume the track.
